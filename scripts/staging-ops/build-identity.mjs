import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";

const digest = (value) => createHash("sha256").update(value).digest("hex");

export function migrationSetIdentity(root = process.cwd()) {
  const schema = readFileSync(path.join(root, "postgres/schema.sql"));
  const migrationDir = path.join(root, "postgres/migrations");
  const migrations = existsSync(migrationDir) ? readdirSync(migrationDir).filter((name) => name.endsWith(".sql")).sort() : [];
  const entries = [
    { path: "postgres/schema.sql", sha256: digest(schema) },
    ...migrations.map((name) => ({ path: `postgres/migrations/${name}`, sha256: digest(readFileSync(path.join(migrationDir, name))) })),
  ];
  return { version: 1, entries, sha256: digest(JSON.stringify(entries)) };
}

/**
 * B4: the importer's TRUSTED IMMUTABLE loader capability — what THIS pinned runner image can
 * replay — read from its own tree and nothing else.
 *
 * The live target catalog must never stand in for this. It is a property of whatever was last
 * installed (or half-installed), so using it as loader identity both blocks a legitimate
 * staging-only schema change and makes recovery from a partially-restored target impossible: the
 * gate that decides whether it is safe to drain would be reading the very state that draining is
 * meant to replace.
 */
export function loaderCapabilityIdentity(root = process.cwd()) {
  return { version: 1, migrationSet: migrationSetIdentity(root) };
}

export function schemaFingerprintDigest(lines) {
  if (!Array.isArray(lines) || lines.length === 0) throw new Error("canonical database schema fingerprint is empty");
  return digest(`${[...lines].sort().join("\n")}\n`);
}

/**
 * Pre-drain compatibility: the signed incoming (or prior) payload's declared build against this
 * runner's immutable loader capability. Exact equality is the default; any supported upgrade path
 * would have to be explicitly versioned and tested, never inferred here.
 */
export function assertCompatibleBuildIdentity(source, loader) {
  if (!source?.applicationCommit || !/^[0-9a-f]{40}$/i.test(source.applicationCommit)) throw new Error("source application commit/build identity is absent or unknown");
  if (!source?.migrationSet?.sha256 || source.migrationSet.sha256 !== loader?.migrationSet?.sha256) {
    throw new Error("runner loader migration set is incompatible with the source build; upgrade the pinned runner image separately");
  }
  if (!source?.schemaFingerprint || !/^[0-9a-f]{64}$/.test(String(source.schemaFingerprint))) {
    throw new Error("source payload declares no canonical database schema fingerprint");
  }
}

/**
 * Post-install verification (B4 "verify installed result"). The bundle declares the catalog digest
 * measured at the SOURCE; the installed target is that dump replayed plus this loader's migrations.
 *
 * A digest difference is REPORTED, never explained away: an upgraded production catalog and a
 * from-zero loader can legitimately diverge (autogenerated constraint names, server-version
 * artefacts — see scripts/schema-fingerprint.mjs), and the correct response is a named diagnostic
 * an operator can act on, not a generic-upgrade code path invented here.
 */
export function assertInstalledSchemaMatches(declared, measuredLines, { context = "installed pair" } = {}) {
  const measured = schemaFingerprintDigest(measuredLines);
  if (declared === measured) return { ok: true, digest: measured };
  throw new Error(
    `${context} catalog digest ${measured} differs from the payload-declared ${declared}; ` +
    `reported for diagnosis, not reconciled — measured catalog census ${catalogCensus(measuredLines)}`
  );
}

/**
 * A bounded, content-free census: counts per catalog kind. The bundle carries the source DIGEST and
 * not its lines, so no line-level diff is derivable here — claiming one would be fabricated. Counts
 * are what this side can honestly report, and they localise the divergence to a kind.
 */
export function catalogCensus(lines) {
  const counts = new Map();
  for (const line of lines ?? []) {
    const kind = String(line).split("\t")[0];
    counts.set(kind, (counts.get(kind) ?? 0) + 1);
  }
  return [...counts.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([kind, count]) => `${kind}=${count}`).join(" ");
}
