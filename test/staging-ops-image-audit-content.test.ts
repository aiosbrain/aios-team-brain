/**
 * PUB-07's local synthetic-image integration test: a hand-built export archive driven through the
 * exact code the runner runs — no Docker, no registry, no network.
 *
 * THE CLAIM IT SUPPORTS, precisely. That the inspector reads every layer's content, including a file
 * a later layer deletes, and stages it where a scanner would see it. It does NOT claim a scan ran,
 * and it says nothing whatsoever about the real pinned digest: these are generated bytes, and
 * "MOCK PASS IS NOT THE LIVE AUDIT" is the spec's own line.
 *
 * Every secret-shaped value here is minted per run by `syntheticSecret`, so this file cannot become
 * a place a real credential hides.
 */

/** The shapes this file reads off the inspector's result. Narrow on purpose: no `any` in a fixture. */
interface LayerSummary {
  index: number;
  form: string;
  members: number;
  expandedBytes: number;
}
interface InventoryMember {
  path: string;
  type: string;
  sha256?: string;
}
interface ComparisonOutcome {
  path: string;
  outcome: string;
}

const scratches: string[] = [];
const scratch = () => {
  const dir = mkdtempSync(join(tmpdir(), "aios-audit-test-"));
  scratches.push(dir);
  return dir;
};
afterAll(() => { for (const dir of scratches) rmSync(dir, { recursive: true, force: true }); });

/** Assemble a synthetic single-platform image and its `docker save`-shaped export. */
function synthesizeImage(layerTars: Buffer[], options: { env?: string[]; history?: string[]; uncompressed?: boolean } = {}) {
  const blobs = layerTars.map((tar) => (options.uncompressed ? tar : gzipSync(tar)));
  const config = {
    architecture: "amd64",
    os: "linux",
    config: {
      Env: options.env ?? ["PATH=/usr/local/bin", "NODE_ENV=production"],
      Entrypoint: ["/usr/bin/tini", "-s", "--", "node"],
      User: "node",
      Labels: {
        "org.opencontainers.image.revision": SUBJECT.sourceRevision,
        "org.opencontainers.image.source": `https://github.com/${SUBJECT.repository}`,
      },
    },
    history: (options.history ?? ["RUN npm ci --ignore-scripts"]).map((created_by) => ({ created_by })),
    rootfs: { type: "layers", diff_ids: layerTars.map((tar) => sha256(tar)) },
  };
  const configBytes = Buffer.from(JSON.stringify(config), "utf8");
  const manifest = {
    schemaVersion: 2,
    mediaType: "application/vnd.oci.image.manifest.v1+json",
    config: { mediaType: "application/vnd.oci.image.config.v1+json", digest: sha256(configBytes), size: configBytes.length },
    layers: blobs.map((blob) => ({
      mediaType: options.uncompressed ? "application/vnd.oci.image.layer.v1.tar" : "application/vnd.oci.image.layer.v1.tar+gzip",
      digest: sha256(blob),
      size: blob.length,
    })),
  };
  const manifestBytes = Buffer.from(JSON.stringify(manifest), "utf8");
  // The export names its blobs however the local store likes — the inspector never reads these names,
  // it looks members up by hash, so deliberately unhelpful names are the honest fixture.
  const exportTar = buildTar([
    { name: "oci-layout", content: '{"imageLayoutVersion":"1.0.0"}' },
    { name: "blobs/sha256/aaaaaaaa", content: configBytes },
    ...blobs.map((blob, index) => ({ name: `blobs/sha256/zzzz${index}`, content: blob })),
  ]);
  return { manifestBytes, manifestDigest: sha256(manifestBytes), exportTar, configBytes, blobs };
}

async function inspect(image: ReturnType<typeof synthesizeImage>) {
  const dir = scratch();
  const exportPath = join(dir, "image.tar");
  writeFileSync(exportPath, image.exportTar);
  const manifest = verifyManifest(image.manifestBytes, image.manifestDigest);
  const result = await inspectExport({ exportPath, manifest, scratchDir: dir, limits: AUDIT_LIMITS, platform: "linux/amd64" });
  return { ...result, dir };
}

/** Everything the scanner would be pointed at, as one string. The scan surface, measured. */
function scanSurface(scanDir: string): string {
  const walk = (dir: string): string[] => readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [readFileSync(full, "utf8")];
  });
  return walk(scanDir).join("\n");
}

describe("a clean synthetic image passes, and the pass is measured (PUB-07)", () => {
  it("verifies identity, inventories every layer, and reports complete coverage", async () => {
    const image = synthesizeImage([
      buildTar([{ name: "app/package.json", content: '{"name":"aios"}' }]),
      buildTar([{ name: "app/index.js", content: "export const ok = true;\n" }]),
    ]);
    const result = await inspect(image);
    expect(result.identityVerified).toBe(true);
    expect(result.layers.map((layer: LayerSummary) => layer.form)).toEqual(["compressed-blob", "compressed-blob"]);
    expect(result.coverage.complete).toBe(true);
    expect(result.coverage.limitations).toEqual([]);
    // A clean pass that read NOTHING would look identical without this: coverage counts are the
    // negative control on the whole result.
    expect(result.coverage.members).toBe(2);
    expect(result.coverage.stagedBytes).toBeGreaterThan(0);
    expect(latestAppMembers(result.appMembers, result.merged).map((m: InventoryMember) => m.path).sort())
      .toEqual(["app/index.js", "app/package.json"]);
  });

  /**
   * THE DEFECT THIS EXISTS FOR. The decode branch was chosen by asking whether the export contained a
   * member hashing to `descriptor.digest`. For an uncompressed `…layer.v1.tar` layer that digest IS
   * the diff_id, so the answer was yes for a plain tar — and the raw tar went to gunzip, which failed
   * with `incorrect header check`. The media type is what says how the bytes are encoded.
   */
  it("reads an UNCOMPRESSED-diff export the same way, without attempting a decode", async () => {
    const image = synthesizeImage([buildTar([{ name: "app/index.js", content: "ok" }])], { uncompressed: true });
    // The precondition that made the old branch fire: for this media type the two digests coincide.
    const manifest = JSON.parse(image.manifestBytes.toString("utf8"));
    expect(manifest.layers[0].mediaType).toBe("application/vnd.oci.image.layer.v1.tar");
    expect(manifest.layers[0].digest).toBe(sha256(image.blobs[0]));

    const result = await inspect(image);
    expect(result.layers[0].form).toBe("uncompressed-diff");
    expect(result.coverage.complete).toBe(true);
    // …and the content really was read, rather than the layer being skipped into a clean-looking pass.
    expect(result.coverage.members).toBe(1);
    expect(scanSurface(result.scanDir)).toContain("ok");
  });

  it("FAILS an uncompressed layer whose descriptor digest is not its diff_id", async () => {
    // A tar layer's blob digest and diff_id are the same bytes by definition. A manifest/config pair
    // that disagrees is inconsistent, and guessing which one to believe is how an audit ends up
    // describing an artifact it did not read.
    const image = synthesizeImage([buildTar([{ name: "app/index.js", content: "ok" }])], { uncompressed: true });
    const config = JSON.parse(image.configBytes.toString("utf8"));
    config.rootfs.diff_ids = [sha256(Buffer.from("some other layer"))];
    const configBytes = Buffer.from(JSON.stringify(config), "utf8");
    const manifest = JSON.parse(image.manifestBytes.toString("utf8"));
    manifest.config.digest = sha256(configBytes);
    manifest.config.size = configBytes.length;
    const manifestBytes = Buffer.from(JSON.stringify(manifest), "utf8");

    const dir = scratch();
    const exportPath = join(dir, "image.tar");
    writeFileSync(exportPath, buildTar([
      { name: "blobs/sha256/aaaaaaaa", content: configBytes },
      { name: "blobs/sha256/zzzz0", content: image.blobs[0] },
    ]));
    await expect(inspectExport({
      exportPath,
      manifest: verifyManifest(manifestBytes, sha256(manifestBytes)),
      scratchDir: dir,
      limits: AUDIT_LIMITS,
      platform: "linux/amd64",
    })).rejects.toThrow(/is not its diff_id/);
  });
});

describe("a secret deleted by a later layer is INVISIBLE merged and still scanned (PUB-02, PUB-07)", () => {
  it("stages the earlier layer's bytes for the scanner and reports the path as shadowed", async () => {
    const secret = syntheticSecret();
    const image = synthesizeImage([
      buildTar([
        { name: "app/index.js", content: "export const ok = true;\n" },
        { name: "app/credentials.json", content: `{"token":"${secret}"}` },
      ]),
      // The later layer deletes it. `docker run` + `cat` would find nothing; the layer blob still
      // ships the bytes to everyone who pulls the digest.
      buildTar([{ name: "app/.wh.credentials.json" }]),
    ]);
    const result = await inspect(image);

    // (1) Invisible in the merged filesystem — the view an inspected container would show.
    expect(result.merged.visible.has("app/credentials.json")).toBe(false);
    expect(result.merged.shadowed).toContainEqual({ path: "app/credentials.json", layer: 0, removedBy: 1, reason: "deleted" });

    // (2) …and PRESENT on the scan surface anyway. This is the whole audit in one assertion.
    expect(scanSurface(result.scanDir)).toContain(secret);

    // (3) The two sets are DIFFERENT, and that is the point. `/app` for the provenance comparison is
    // what survives — a deleted path is not a provenance question about the image's file tree — while
    // the scan above covered the bytes that still ship. A `latestAppMembers` that took the last
    // WRITER instead of the surviving member would put `app/credentials.json` back in this list.
    const shipped = latestAppMembers(result.appMembers, result.merged).map((m: InventoryMember) => m.path);
    expect(shipped).toEqual(["app/index.js"]);
    expect(shipped).not.toContain("app/credentials.json");
  });

  it("does the same for a file OVERWRITTEN by a later layer", async () => {
    const oldSecret = syntheticSecret();
    const image = synthesizeImage([
      buildTar([{ name: "app/.env.local", content: `TOKEN=${oldSecret}` }]),
      buildTar([{ name: "app/.env.local", content: "TOKEN=redacted-later" }]),
    ]);
    const result = await inspect(image);
    expect(result.merged.visible.get("app/.env.local")).toBe(1);
    expect(scanSurface(result.scanDir)).toContain(oldSecret);
  });
});

