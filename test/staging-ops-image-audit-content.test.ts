describe("coverage gaps are REPORTED, never silently narrowed (PUB-03)", () => {
  it("records an unexpandable archive format instead of calling opaque bytes inspected", async () => {
    const image = synthesizeImage([buildTar([{ name: "app/vendor/bundle.zip", content: "PK opaque" }])]);
    const result = await inspect(image);
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.limitations).toContainEqual({ kind: "unexpanded-archive-format", layer: 0, extension: ".zip" });
  });

  it("records an oversized member instead of scanning a truncated copy of it", async () => {
    const image = synthesizeImage([buildTar([{ name: "app/big.bin", content: Buffer.alloc(4096, 7) }])]);
    const dir = scratch();
    const exportPath = join(dir, "image.tar");
    writeFileSync(exportPath, image.exportTar);
    const manifest = verifyManifest(image.manifestBytes, image.manifestDigest);
    const result = await inspectExport({
      exportPath, manifest, scratchDir: dir, platform: "linux/amd64",
      limits: { ...AUDIT_LIMITS, maxMemberBytes: 1024 },
    });
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.limitations).toContainEqual({ kind: "oversized-member", layer: 0, bytes: 4096 });
  });

  it("records an unknown member TYPE instead of passing over bytes nobody inspected", async () => {
    const image = synthesizeImage([buildTar([
      { name: "app/index.js", content: "ok" },
      { name: "app/odd", content: "unread bytes", rawTypeflag: "M" },
    ])]);
    const result = await inspect(image);
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.limitations).toContainEqual({ kind: "unsupported-member-type", layer: 0, typeflag: "M" });
  });

  it("does not echo an attacker-chosen typeflag into the evidence", async () => {
    // One attacker-controlled byte, and limitations reach the PUBLIC artifact. Non-printables are
    // reported by category rather than passed through.
    //
    // Written as an escape, never as a literal control byte in this file: a raw non-printable is
    // invisible in review, and one byte over (`\0`) would make git treat the source as binary.
    const image = synthesizeImage([buildTar([{ name: "app/odd", content: "x", rawTypeflag: String.fromCharCode(1) }])]);
    const result = await inspect(image);
    expect(result.coverage.limitations).toContainEqual({ kind: "unsupported-member-type", layer: 0, typeflag: "non-printable" });
  });

  it("EXPANDS a nested tar.gz so its contents reach the scanner", async () => {
    const secret = syntheticSecret();
    const nested = gzipSync(buildTar([{ name: "fixture/key.txt", content: secret }]));
    const image = synthesizeImage([buildTar([{ name: "app/node_modules/pkg/test.tar.gz", content: nested }])]);
    const result = await inspect(image);
    // Left opaque, this file is gzip bytes and every rule reports clean. The expansion is the
    // difference between scanning a package and scanning its wrapper.
    expect(scanSurface(result.scanDir)).toContain(secret);
  });

  /**
   * PUB-01's CUMULATIVE bound. Each layer here is comfortably inside `maxExpandedBytesPerLayer`, and
   * together they exceed the total — which is the case a per-layer limit cannot catch, and the reason
   * "64 layers × 6 GiB" was never actually bounded.
   */
  it("stops staging at the TOTAL byte bound, even when every layer is individually within its limit", async () => {
    const perLayer = 4096;
    const image = synthesizeImage([
      buildTar([{ name: "app/first.bin", content: Buffer.alloc(perLayer, 1) }]),
      buildTar([{ name: "app/second.bin", content: Buffer.alloc(perLayer, 2) }]),
    ]);
    const dir = scratch();
    const exportPath = join(dir, "image.tar");
    writeFileSync(exportPath, image.exportTar);
    const result = await inspectExport({
      exportPath,
      manifest: verifyManifest(image.manifestBytes, image.manifestDigest),
      scratchDir: dir,
      platform: "linux/amd64",
      limits: {
        ...AUDIT_LIMITS,
        // Each layer is allowed its whole content; the RUN is allowed only the first one's worth.
        maxExpandedBytesPerLayer: perLayer * 4,
        maxMemberBytes: perLayer * 4,
        maxTotalStagedBytes: perLayer + 1,
      },
    });

    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.limitations).toContainEqual({ kind: "total-staging-budget-exhausted", layer: 1 });
    // The FIRST layer is unaffected — a total bound must stop staging, not retroactively invalidate
    // what was already read.
    expect(result.coverage.stagedBytes).toBe(perLayer);
    expect(scanSurface(result.scanDir)).toContain(Buffer.alloc(perLayer, 1).toString("utf8"));
    // …and the refused member left NO partial file behind for the scanner to read as a whole one.
    expect(scanSurface(result.scanDir)).not.toContain(Buffer.alloc(1, 2).toString("utf8"));
    // Identity is still verified for every layer: the bound is about how much content was staged,
    // not about which layers exist.
    expect(result.layers).toHaveLength(2);
  });

  it("counts a NESTED archive's expansion against the same total bound", async () => {
    const secret = syntheticSecret();
    const nested = gzipSync(buildTar([{ name: "fixture/key.txt", content: secret }]));
    const image = synthesizeImage([buildTar([
      { name: "app/a.js", content: "x".repeat(64) },
      { name: "app/node_modules/pkg/test.tar.gz", content: nested },
    ])]);
    const dir = scratch();
    const exportPath = join(dir, "image.tar");
    writeFileSync(exportPath, image.exportTar);
    const result = await inspectExport({
      exportPath,
      manifest: verifyManifest(image.manifestBytes, image.manifestDigest),
      scratchDir: dir,
      platform: "linux/amd64",
      // Enough for the two layer members, not for the inflated copy of the nested archive: an
      // expansion that ignored the budget is how a decompression bomb fills a runner disk.
      limits: { ...AUDIT_LIMITS, maxTotalStagedBytes: 64 + nested.length },
    });
    expect(result.coverage.limitations).toContainEqual({ kind: "total-staging-budget-exhausted", layer: 0 });
    expect(scanSurface(result.scanDir)).not.toContain(secret);
  });

  it("FAILS a missing layer rather than auditing the layers it did find", async () => {
    const image = synthesizeImage([
      buildTar([{ name: "app/a.js", content: "1" }]),
      buildTar([{ name: "app/b.js", content: "2" }]),
    ]);
    // Drop the second blob from the export, leaving the manifest still declaring two layers. The
    // FIRST blob is reused verbatim, so the only difference from the passing case is the absence —
    // re-gzipping it would risk failing for a byte-level reason this case is not about.
    const dir = scratch();
    const exportPath = join(dir, "image.tar");
    const manifest = verifyManifest(image.manifestBytes, image.manifestDigest);
    writeFileSync(exportPath, buildTar([
      { name: "blobs/sha256/aaaaaaaa", content: image.configBytes },
      { name: "blobs/sha256/zzzz0", content: image.blobs[0] },
    ]));
    await expect(inspectExport({ exportPath, manifest, scratchDir: dir, limits: AUDIT_LIMITS, platform: "linux/amd64" }))
      .rejects.toThrow(/missing layer/);
  });
});

describe("the /app inventory: dockerignore filters the EXPECTED set only (M1)", () => {
  const dockerignore = ["node_modules", ".next", ".git", ".env", ".env.*", "!.env.example", ".context", "*.log"].join("\n");
  const sourceEntries = [
    { path: "package.json", type: "file", sha256: sha256(Buffer.from("{}")).slice(7) },
    { path: "lib/index.ts", type: "file", sha256: sha256(Buffer.from("export {}")).slice(7) },
    { path: ".env.example", type: "file", sha256: sha256(Buffer.from("KEY=")).slice(7) },
    { path: ".env.production", type: "file", sha256: "deadbeef" },
    { path: ".context/notes.md", type: "file", sha256: "cafebabe" },
  ];

  it("honours last-match-wins negation, so `.env.example` is expected and `.env.production` is not", () => {
    const excluded = dockerignoreMatcher(dockerignore);
    expect(excluded(".env.example")).toBe(false);
    expect(excluded(".env.production")).toBe(true);
    expect(excluded("node_modules/react/index.js")).toBe(true);
    expect(excluded(".context/notes.md")).toBe(true);
    expect(excluded("lib/index.ts")).toBe(false);
  });

  it("calls an EXCLUDED path present in the image a FINDING, never a scan skip", () => {
    const expected = expectedInventory(sourceEntries, dockerignore);
    const comparison = compareInventory([
      { path: "app/package.json", type: "file", sha256: sourceEntries[0].sha256 },
      // The two paths `.dockerignore` said would never be in the context. If exclusions filtered the
      // ACTUAL set, these would vanish from the report — the exact inversion M1 rules out.
      { path: "app/.env.production", type: "file", sha256: "deadbeef" },
      { path: "app/.context/notes.md", type: "file", sha256: "cafebabe" },
    ], expected);
    const outcomes = Object.fromEntries(comparison.outcomes.map((o: ComparisonOutcome) => [o.path, o.outcome]));
    expect(outcomes["app/.env.production"]).toBe("excluded-path");
    expect(outcomes["app/.context/notes.md"]).toBe("excluded-path");
    expect(outcomes["app/package.json"]).toBe("matched");
  });

  it("flags a first-party file whose bytes differ from the Git blob", () => {
    const expected = expectedInventory(sourceEntries, dockerignore);
    const comparison = compareInventory([{ path: "app/lib/index.ts", type: "file", sha256: "0".repeat(64) }], expected);
    expect(comparison.outcomes[0].outcome).toBe("content-mismatch");
  });

  it("accounts for dependencies and build output as CATEGORIES, which are not exemptions", () => {
    // Accounting explains why a path has no Git blob. It does not remove the file from the scan —
    // that surface is proved separately by the nested-archive case above.
    expect(provenanceCategory("app/node_modules/react/index.js")).toBe("npm-dependency");
    expect(provenanceCategory("app/node_modules/.package-lock.json")).toBe("npm-dependency");
    expect(provenanceCategory("app/.next/BUILD_ID")).toBe("next-build-dir");
    expect(provenanceCategory("app/src/unexpected-generated.js")).toBeUndefined();
  });

  it("reports an unexpected generated path and a missing expected path as findings", () => {
    const expected = expectedInventory(sourceEntries, dockerignore);
    const summary = inventorySummary(compareInventory([
      { path: "app/package.json", type: "file", sha256: sourceEntries[0].sha256 },
      { path: "app/build-artifact.bin", type: "file", sha256: "abc" },
    ], expected));
    expect(summary.counts.unexpected).toBe(1);
    // `.env.example` and `lib/index.ts` were expected and absent — the comparison is INCOMPLETE, and
    // an incomplete comparison must not read as a clean one.
    expect(summary.counts.missing).toBe(2);
    expect(summary.complete).toBe(false);
    expect(summary.findings).toBe(3);
  });

  it("compares symlinks as links, without following them", () => {
    const expected = expectedInventory(
      [{ path: "bin/cli", type: "symlink", linkTarget: "../lib/cli.js" }],
      dockerignore,
    );
    const same = compareInventory([{ path: "app/bin/cli", type: "symlink", linkTarget: "../lib/cli.js" }], expected);
    const moved = compareInventory([{ path: "app/bin/cli", type: "symlink", linkTarget: "/etc/passwd" }], expected);
    expect(same.outcomes[0].outcome).toBe("matched");
    expect(moved.outcomes[0].outcome).toBe("content-mismatch");
  });
});
