const teamOfMember = async (memberId: string): Promise<unknown> =>
  (await fxOne("member team readback", `select team_id from members where id = $1`, [memberId])).team_id;

const teamOfKey = async (rowId: string): Promise<unknown> =>
  (await fxOne("key team readback", `select team_id from api_keys where id = $1`, [rowId])).team_id;

/** Each named key row as the pool reads it back: live while `revoked_at` is null. */
async function liveness(rows: Record<string, string>): Promise<Record<string, string>> {
  const read: Record<string, string> = {};
  for (const [label, id] of Object.entries(rows)) {
    const { revoked_at } = await fxOne<{ revoked_at: Date | null }>(
      `${label} key readback`,
      `select revoked_at from api_keys where id = $1`,
      [id],
    );
    read[label] = revoked_at === null ? "live" : "revoked";
  }
  return read;
}

function rowOf(snapshot: Durable, rowId: string): Row {
  const row = snapshot.api_keys.find((candidate) => candidate.id === rowId);
  if (!row) throw new Error(`${FIXTURE} no api_keys row ${rowId} in the snapshot`);
  return row;
}

// ── the calls ────────────────────────────────────────────────────────────────────────────────────

/** The option both primitives take: the supplied member as the actor. */
const actorOf = (memberId: string) => ({ actor: { kind: "member" as const, memberId } });

async function settle(start: () => Promise<unknown>): Promise<Settled> {
  try {
    return { returned: await start() };
  } catch (thrown) {
    return {
      rejected: { error: thrown instanceof Error, message: thrown instanceof Error ? thrown.message : String(thrown) },
    };
  }
}

/** Snapshot, run the one call, snapshot again. */
async function observe(start: () => Promise<unknown>): Promise<Seen> {
  const before = await durable();
  const earliest = Date.now();
  const outcome = await settle(start);
  const latest = Date.now();
  const after = await durable();
  return { outcome, before, after, changed: changes(before, after), window: { earliest, latest } };
}

/** An issue call reduced to its key id, so no settled outcome can carry the credential. */
const keyIdOnly = async (call: Promise<{ key: string; keyId: string }>): Promise<{ keyId: string }> => ({
  keyId: (await call).keyId,
});

/**
 * One real `issueApiKey` call that must be admitted, and everything that may be said about its
 * credential. The raw string and its secret do not leave this function.
 */
async function issue(teamId: string, memberId: string, name: string, actor: string): Promise<Issued> {
  const before = await durable();
  const { key, keyId } = await issueApiKey(db(), teamId, memberId, name, actorOf(actor));
  const after = await durable();

  const prefix = `aios_${keyId}_`;
  const secret = key.startsWith(prefix) ? key.slice(prefix.length) : key;
  // Compared in this process only: the secret is never bound into a statement.
  const persisted = JSON.stringify(after);
  return {
    keyId,
    wellFormed: key.startsWith(prefix) && KEY_ID.test(keyId) && SECRET.test(secret),
    secretSha256: sha(secret),
    persistedRaw: persisted.includes(key) || persisted.includes(secret),
    changed: changes(before, after),
  };
}

/** A fixture key issued by the real primitive, as the `api_keys` row id a revoke is handed. */
async function issuedRow(teamId: string, memberId: string, name: string, actor: string): Promise<string> {
  const { keyId } = await issue(teamId, memberId, name, actor);
  return (await fxOne<{ id: string }>("issued row id", `select id from api_keys where key_id = $1`, [keyId])).id;
}

