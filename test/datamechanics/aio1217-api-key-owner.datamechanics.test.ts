const FIXTURE = "FIXTURE PREMISE FAILED (setup, not an owner observation):";
const CONTROL = "ADMITTED CONTROL FAILED (the paired observation would be vacuous):";

type Row = Record<string, unknown>;

/** Two teams, several issued keys, and whole-rowset snapshots around each call. */
const ROOMY = 30_000;

/** `randomBytes(6)` as hex and `randomBytes(32)` as unpadded base64url: what the primitive generates. */
const KEY_ID = /^[0-9a-f]{12}$/;
const SECRET = /^[A-Za-z0-9_-]{43}$/;

interface World {
  a: Seed;
  b: Seed;
  /** A second active member of team A: the actor every team-A call is supplied with. */
  actor: string;
}

/** How a call ended: what it returned, or how its rejection classifies. */
type Settled = { returned: unknown } | { rejected: { error: boolean; message: string } };

interface Seen {
  outcome: Settled;
  before: Durable;
  after: Durable;
  changed: Changed;
  /** This process's clock immediately around the call. */
  window: { earliest: number; latest: number };
}

/** One admitted issue, with the credential already reduced to what may be compared and printed. */
interface Issued {
  keyId: string;
  /** Whether the returned credential was exactly `aios_<returned key id>_<secret>`. */
  wellFormed: boolean;
  /** sha256 of the secret part alone: what the row may hold. */
  secretSha256: string;
  /** Whether the raw credential or its secret occurs in any `api_keys` or `audit_log` value afterwards. */
  persistedRaw: boolean;
  changed: Changed;
}

// ── fixture plumbing ─────────────────────────────────────────────────────────────────────────────

async function fx<T extends Row = Row>(label: string, text: string, params: unknown[] = []): Promise<T[]> {
  try {
    return (await getPool().query(text, params)).rows as T[];
  } catch (error) {
    throw new Error(`${FIXTURE} ${label}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function fxOne<T extends Row = Row>(label: string, text: string, params: unknown[] = []): Promise<T> {
  const rows = await fx<T>(label, text, params);
  if (rows.length !== 1) throw new Error(`${FIXTURE} ${label}: expected exactly one row, got ${rows.length}`);
  return rows[0];
}

function premise(label: string, actual: unknown, expected: unknown): void {
  expect(actual, `${FIXTURE} ${label}`).toEqual(expected);
}

// The two tables the primitives write.
const OWNED_TABLES = ["api_keys", "audit_log"] as const;
type OwnedTable = (typeof OWNED_TABLES)[number];
type Durable = Record<OwnedTable, Row[]>;
type Changed = Partial<Record<OwnedTable, { added: Row[]; removed: Row[] }>>;

/** Every row of both tables, every column, in an order that depends on content only. */
async function durable(): Promise<Durable> {
  const snapshot = {} as Durable;
  for (const table of OWNED_TABLES) {
    const rows = await fx<{ row: Row }>(
      `${table} snapshot`,
      `select to_jsonb(t) as row from ${table} t order by to_jsonb(t)::text`,
    );
    snapshot[table] = rows.map((entry) => entry.row);
  }
  return snapshot;
}

/** The rows a call added and removed, per table; a changed row is one of each. Empty when none. */
function changes(before: Durable, after: Durable): Changed {
  const changed: Changed = {};
  for (const table of OWNED_TABLES) {
    const was = new Set(before[table].map((row) => JSON.stringify(row)));
    const is = new Set(after[table].map((row) => JSON.stringify(row)));
    const added = after[table].filter((row) => !was.has(JSON.stringify(row)));
    const removed = before[table].filter((row) => !is.has(JSON.stringify(row)));
    if (added.length > 0 || removed.length > 0) changed[table] = { added, removed };
  }
  return changed;
}

/** A second active member of the team. Supplied to the primitives as the actor; authorized by nothing. */
async function seedActor(team: Seed): Promise<string> {
  const { data, error } = await db()
    .from("members")
    .insert({
      team_id: team.teamId,
      email: `${randomUUID()}@test.local`,
      display_name: "AIO1217 supplied actor",
      actor_handle: `actor-${randomUUID().slice(0, 8)}`,
      role: "member",
      tier: "team",
      status: "active",
    })
    .select("id")
    .single();
  if (error || !data) throw new Error(`${FIXTURE} actor insert: ${error?.message}`);
  return (data as { id: string }).id;
}

/** Two teams, each with its seeded member. The other team's rows are bystanders. */
